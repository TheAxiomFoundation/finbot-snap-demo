"use client";

import { useEffect, useState } from "react";

import type { Country } from "@/lib/catalog";
import { Chat } from "@/components/Chat";

interface FinBotPageProps {
  initialCountry: Country;
}

export function FinBotPage({ initialCountry }: FinBotPageProps) {
  const [country, setCountry] = useState<Country>(initialCountry);

  useEffect(() => {
    setCountry(initialCountry);
  }, [initialCountry]);

  useEffect(() => {
    const url = new URL(window.location.href);
    if (country === "us") url.searchParams.delete("country");
    else url.searchParams.set("country", country);
    window.history.replaceState({}, "", url.toString());
  }, [country]);

  const isUS = country === "us";
  return (
    <>
      <header className="topbar">
        <div className="topbar-inner">
          <span className="brand-group">
            <a
              href="https://axiom-foundation.org"
              target="_blank"
              rel="noreferrer"
              className="brand-link"
              aria-label="Axiom Foundation"
            >
              <img
                src="/axiom-foundation.svg"
                alt="Axiom Foundation"
                className="brand-axiom"
              />
            </a>
            <span className="brand-divider" aria-hidden="true" />
            <span className="brand-product">FinBot</span>
          </span>
          <div className="country-toggle" role="tablist" aria-label="Country">
            <button
              type="button"
              role="tab"
              aria-selected={isUS}
              className={`country-toggle-btn ${isUS ? "country-toggle-btn-active" : ""}`}
              onClick={() => setCountry("us")}
            >
              US
            </button>
            <button
              type="button"
              role="tab"
              aria-selected={!isUS}
              className={`country-toggle-btn ${!isUS ? "country-toggle-btn-active" : ""}`}
              onClick={() => setCountry("uk")}
            >
              UK
            </button>
          </div>
        </div>
      </header>

      <main style={{ maxWidth: 980, margin: "0 auto", padding: "56px 20px 80px" }}>
        <div className="page-intro" style={{ marginBottom: 36 }}>
          {isUS ? (
            <>
              <h1>
                A benefits assistant powered by the <em>Axiom rules engine</em>.
              </h1>
              <p>
                Every dollar and eligibility verdict is computed against the
                SNAP rulebooks for Colorado, California, and New York — not
                generated by the language model on top.
              </p>
            </>
          ) : (
            <>
              <h1>
                A UK tax and benefits assistant powered by the{" "}
                <em>Axiom rules engine</em>.
              </h1>
              <p>
                Every pound amount is computed against UK personal-allowance
                and Universal Credit rules — not generated by the language
                model on top.
              </p>
            </>
          )}
        </div>

        <Chat country={country} />
      </main>
    </>
  );
}
